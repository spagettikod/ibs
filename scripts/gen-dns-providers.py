#!/usr/bin/env python3
"""Generates internal/tlscert/providers_gen.go: the DNS providers IBS includes,
with the settings each one takes, from lego's provider descriptions.

    scripts/gen-dns-providers.py

Edit PROVIDERS to add or remove one (each adds to the binary size)."""
import json, os, re, subprocess, tomllib

# lego code -> Go package
PROVIDERS = {
    "acme-dns": "acmedns", "allinkl": "allinkl", "bunny": "bunny", "cloudflare": "cloudflare",
    "cloudns": "cloudns", "desec": "desec", "digitalocean": "digitalocean", "dnsimple": "dnsimple",
    "duckdns": "duckdns", "dynu": "dynu", "easydns": "easydns", "exec": "exec", "freemyip": "freemyip",
    "gandiv5": "gandiv5", "glesys": "glesys", "godaddy": "godaddy", "hetzner": "hetzner",
    "hostingde": "hostingde", "httpreq": "httpreq", "hurricane": "hurricane", "infomaniak": "infomaniak",
    "inwx": "inwx", "ionos": "ionos", "ipv64": "ipv64", "linode": "linode", "loopia": "loopia",
    "mythicbeasts": "mythicbeasts", "namecheap": "namecheap", "namedotcom": "namedotcom",
    "namesilo": "namesilo", "netcup": "netcup", "netlify": "netlify", "njalla": "njalla", "ovh": "ovh",
    "pdns": "pdns", "porkbun": "porkbun", "rfc2136": "rfc2136", "route53": "route53",
    "scaleway": "scaleway", "transip": "transip", "vultr": "vultr", "websupport": "websupport",
}
# Fields lego documents only in prose.
EXTRA = {
    "exec": {"Credentials": {"EXEC_PATH": "Path of the program to run, inside the manager's container"},
             "Additional": {"EXEC_MODE": "`RAW` passes the domain, token and key instead of the record name and value"}},
}
SECRET = re.compile(r"(SECRET|TOKEN|PASSWORD|PASS|_KEY|APIKEY)$")

root = os.path.join(os.path.dirname(__file__), "..")
mod = subprocess.check_output(["go", "list", "-m", "-f", "{{.Dir}}", "github.com/go-acme/lego/v4"], cwd=root, text=True).strip()
version = subprocess.check_output(["go", "list", "-m", "-f", "{{.Version}}", "github.com/go-acme/lego/v4"], cwd=root, text=True).strip()

def fields(section):
    out = []
    for name, desc in (section or {}).items():
        if desc.startswith("Alias to"):
            continue
        out.append({"name": name, "description": desc.strip(), "secret": bool(SECRET.search(name))})
    return out

entries, imports, ctors = [], [], []
for code, pkg in sorted(PROVIDERS.items()):
    with open(os.path.join(mod, "providers", "dns", pkg, pkg + ".toml"), "rb") as f:
        t = tomllib.load(f)
    conf = t.get("Configuration", {}) or EXTRA.get(code, {})
    entries.append({"code": code, "name": t["Name"], "docs": f"https://go-acme.github.io/lego/dns/{code}/",
                    "credentials": fields(conf.get("Credentials")), "additional": fields(conf.get("Additional"))})
    imports.append(f'\t"github.com/go-acme/lego/v4/providers/dns/{pkg}"')
    ctors.append(f'\t"{code}": func() (challenge.Provider, error) {{ return {pkg}.NewDNSProvider() }},')

def go_fields(fs):
    return "".join(f'\n\t\t\t{{Name: {json.dumps(x["name"])}, Description: {json.dumps(x["description"])}, Secret: {str(x["secret"]).lower()}}},' for x in fs)

meta = "\n".join(
    f'\t{{Code: {json.dumps(e["code"])}, Name: {json.dumps(e["name"])}, Docs: {json.dumps(e["docs"])},\n'
    f'\t\tCredentials: []Field{{{go_fields(e["credentials"])}\n\t\t}},\n'
    f'\t\tAdditional: []Field{{{go_fields(e["additional"])}\n\t\t}},\n\t}},'
    for e in entries)

src = f'''// Code generated by scripts/gen-dns-providers.py from lego {version}; DO NOT EDIT.

package tlscert

import (
	"github.com/go-acme/lego/v4/challenge"
{chr(10).join(imports)}
)

var constructors = map[string]func() (challenge.Provider, error){{
{chr(10).join(ctors)}
}}

var providerList = []Provider{{
{meta}
}}
'''
out = os.path.join(root, "internal", "tlscert", "providers_gen.go")
with open(out, "w") as f:
    f.write(src)
subprocess.check_call(["gofmt", "-w", out])
print(f"wrote {out}: {len(entries)} providers")
